/**
 * Generates `src/generated/SchemaTypes.ts` from `schema/v1/*.schema.json` with
 * json-schema-to-typescript. All schemas are compiled through one in-memory
 * bundle so that every titled definition is declared exactly once.
 */
import { readFileSync, readdirSync } from 'node:fs'
import { join } from 'node:path'
import { compile } from 'json-schema-to-typescript'
import type { JSONSchema } from 'json-schema-to-typescript'
import { format, resolveConfig } from 'prettier'

const packageRoot = join(import.meta.dirname, '..')
const schemaDirectory = join(packageRoot, 'schema/v1')
export const generatedTypesPath = join(packageRoot, 'src/generated/SchemaTypes.ts')

const BANNER = `// SPDX-License-Identifier: AGPL-3.0-or-later
/**
 * GENERATED by scripts/generate-types.ts from schema/v1/*.schema.json.
 * Do not edit by hand: change the schema and run \`npm run generate -w @monki-focus/rules\`.
 * A test fails when this file and the schemas drift apart.
 */`

interface SchemaFile {
  fileName: string
  schema: Record<string, unknown>
}

function readSchemaFiles(): SchemaFile[] {
  return readdirSync(schemaDirectory)
    .filter((fileName) => fileName.endsWith('.schema.json'))
    .sort()
    .map((fileName) => ({
      fileName,
      schema: JSON.parse(readFileSync(join(schemaDirectory, fileName), 'utf8')) as Record<
        string,
        unknown
      >,
    }))
}

/** One property per schema root that is a type of its own and per `$defs` entry. */
function bundleOf(files: SchemaFile[]): JSONSchema {
  const properties: Record<string, JSONSchema> = {}
  for (const { fileName, schema } of files) {
    // The fixture envelope only dispatches on `kind`; src/Fixture.ts declares the union.
    const hasRootType =
      fileName !== 'fixture.schema.json' && ('type' in schema || 'oneOf' in schema)
    if (hasRootType) properties[fileName] = { $ref: fileName }
    const defs = (schema.$defs ?? {}) as Record<string, unknown>
    for (const name of Object.keys(defs).sort()) {
      properties[`${fileName}#${name}`] = { $ref: `${fileName}#/$defs/${name}` }
    }
  }
  return {
    title: 'RulesSchemaBundle',
    description: 'Synthetic root that pulls every schema in; not a document type.',
    type: 'object',
    additionalProperties: false,
    properties,
  }
}

export async function generateSchemaTypes(): Promise<string> {
  const files = readSchemaFiles()
  const source = await compile(bundleOf(files), 'RulesSchemaBundle', {
    cwd: schemaDirectory,
    bannerComment: BANNER,
    additionalProperties: false,
    unreachableDefinitions: false,
    strictIndexSignatures: true,
    ignoreMinAndMaxItems: true,
    format: false,
    $refOptions: { resolve: { http: false } },
  })
  const config = (await resolveConfig(generatedTypesPath)) ?? {}
  return format(source, { ...config, parser: 'typescript' })
}
